test('backups import visible World lore and binary images as independent local copies', async () => {
  const f = await fixture()
  const hidden = await p.createCodexEntry(f.world.id, 'Hidden canon')
  await w.setWorldEntryHidden(f.books[1].id, hidden.id, true)
  const pngBytes = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6AAAAAElFTkSuQmCC', 'base64')
  const png = new Blob([pngBytes], { type: 'image/png' })
  const pixels = { image: png, thumbnail: png, width: 1, height: 1 }
  await p.saveIllustration(f.source.id, pixels, { alt: 'Tower', caption: '', cropX: 0, cropY: 0, cropZoom: 1 })
  const canonical = await f.canonical(f.books[1])
  const archive = await decodeBookArchive(await encodeBookArchive(await p.readBookArchive(f.books[1].id)))
  const copied = copyBookArchive(archive)
  await p.writeBookArchive(copied.data)
  const entries = await p.listEntitiesByBook(copied.bookId, 'codexEntry')
  assert.equal(entries.length, 1)
  const entry = entries[0]
  assert.notEqual(entry.id, f.source.id)
  assert.equal(entry.worldId, undefined); assert.equal(entry.seriesSourceId, undefined); assert.equal(entry.codexScope, undefined)
  assert.equal((await p.getEntity(copied.bookId)).worldId, undefined)
  assert.equal(entry.content, canonical.content)
  assert.deepEqual(entry.autoIncludeTriggers, canonical.autoIncludeTriggers)
  const image = await p.getIllustration(entry.id)
  assert.equal(image.bookId, copied.bookId); assert.equal(image.id, entry.primaryImageId)
  for (const blob of [image.image, image.thumbnail]) {
    assert.equal(blob.type, 'image/png'); assert.equal(blob.size, pngBytes.length)
    assert.equal(Buffer.from(await blob.arrayBuffer()).equals(pngBytes), true)
  }
  assert.notEqual(image.id, canonical.primaryImageId)
  await p.saveDocumentContent(f.source.id, 'Changed after import')
  assert.equal((await p.getEntity(entry.id)).content, canonical.content)
})
test('joining a World keeps local entries local; conflicting moves never overwrite canonical data', async () => {
  const f = await fixture(), newcomer = (await p.createBook(initialAiSettings, 'Newcomer')).book
  const duplicate = await p.createCodexEntry(newcomer.id, 'The tower')
  await p.updateCodexAutoIncludeTriggers(duplicate.id, ['The tower'])
  await p.saveDocumentContent(duplicate.id, 'Local duplicate')
  await w.setBookWorld(newcomer.id, f.world.id)
  assert.deepEqual(ids(await p.listEntitiesByBook(newcomer.id, 'codexEntry')), ids([duplicate, f.source]))
  await assert.rejects(() => w.moveEntryToWorld(newcomer.id, duplicate.id), /trigger conflict/i)
  assert.equal((await p.getEntity(duplicate.id)).content, 'Local duplicate')
  assert.equal((await p.getEntity(duplicate.id)).worldId, undefined)
  assert.equal((await p.getEntity(f.source.id)).content, 'A red tower')
  await p.saveDocumentContent(f.source.id, 'Approved canonical edit')
  assert.equal((await f.canonical(newcomer)).content, 'Approved canonical edit')
  assert.equal((await p.getEntity(duplicate.id)).content, 'Local duplicate')
})
